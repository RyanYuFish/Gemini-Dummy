#!/usr/bin/env python3
"""在 guest 里执行脚本 / 采集信息。

用法:
  shrun.py 'cmd1' 'cmd2' ...            # 逐条执行命令并按 echo MK<n> 标记切分输出
  shrun.py --script <本地文件>           # 把本地脚本 base64 送到 guest 执行

--script 模式解决多层 shell 引号地狱：脚本在宿主侧写好，base64 编码，
guest 用 busybox base64 -d 解码后执行，脚本内容一个字都不用转义。

guest 侧落盘: /tmp/_shrun.sh   脚本应把结果写到 /tmp/_shrun.out
"""
import base64
import os
import re
import socket
import subprocess
import sys
import threading
import time

LAB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIN = f"{LAB}/qemu-src/build/qemu-system-arm"
KERNEL = os.environ.get("SP_KERNEL", f"{LAB}/images/kernel-ae5i.bin")
PORT = int(os.environ.get("SP_SH_PORT", "4501"))
MTDPARTS = ("mtdparts=sp_spinand.0:0x40000(nand_header),0x40000(xboot1),"
            "0xc0000(uboot1),0x1c0000(uboot2),0x80000(env),0x80000(env_redund),"
            "0x400000(ecos),0x480000(kernel),0x480000(rootfs.),0x80000(opt.),"
            "0x3000000(spsdk.),0x4040000(spapp.),0x1000000(nvm),0x40000(pq),"
            "0x40000(tcon),0x40000(iop_car),0x40000(runtime_cfg),0x40000(vi),"
            "0x980000(isp_logo),0x40000(vendordata),0xbc0000(pat_logo),"
            "0x40000(version_info),0x40000(vd_restore),0x1000000(anm_logo),"
            "0x15540000(userdata)")
APPEND = " ".join(["console=ttyS0,921600", "loglevel=7", "panic=1", MTDPARTS,
                   "res_chunkmem=0x04000000@0x0C000000",
                   "res_fb0=0x00600000@0x0C000000",
                   "res_fb1=0x00600000@0x0C600000",
                   "res_fb2=0x00600000@0x0CC00000"])
env = dict(os.environ)
env["SP_VDISK"] = os.environ.get("SP_VDISK", f"{LAB}/images/ae5i.spvd")
# Optional QEMU-only rootfs variant generated by prepare_software_display.py.
# It keeps the factory SPVD untouched and makes DirectFB's software fallback
# deterministic while galcore is still being completed.
# The complete emulator profile supplies the currently implemented eCos/GD32
# mailbox peer so the stock init sequence can reach the Launcher. Set
# SP_COMPLETE_BOOT=0 to inspect the strict no-peer baseline; SP_IPC_STUB still
# overrides the profile explicitly.
profile = os.environ.get("SP_COMPLETE_BOOT", "1").lower()
ipc_requested = os.environ.get("SP_IPC_STUB")
if ipc_requested is None and profile not in ("", "0", "false", "off", "no"):
    ipc_requested = "1"
ipc_stub = (ipc_requested or "").lower()
if ipc_stub not in ("", "0", "false", "off", "no"):
    env["SP_IPC_STUB"] = ipc_requested
else:
    env.pop("SP_IPC_STUB", None)

log = open("/tmp/shr.log", "wb")
err = open("/tmp/shr.err", "wb")
serial_args = ["-chardev", f"socket,host=127.0.0.1,port={PORT},server=on,wait=off,id=c0",
               "-serial", "chardev:c0"]
if os.environ.get("SP_CFCP_PORT"):
    cfcp_port = int(os.environ["SP_CFCP_PORT"])
    serial_args += ["-chardev", f"socket,host=127.0.0.1,port={cfcp_port},server=on,wait=off,id=cfcp",
                    "-serial", "chardev:cfcp"]
p = subprocess.Popen(
    [BIN, "-M", "sunplus-sp8368", "-m", "256", "-kernel", KERNEL, "-append", APPEND,
     *serial_args, "-display", "none", "-monitor", "none", "-no-reboot"],
    env=env, stdout=subprocess.DEVNULL, stderr=err)

buf = bytearray()
stop = [False]
sock = [None]


def reader():
    s = None
    t0 = time.time()
    while time.time() - t0 < 40 and s is None:
        try:
            s = socket.create_connection(("127.0.0.1", PORT), 2)
        except OSError:
            time.sleep(0.2)
    if s is None:
        print("connect failed")
        return
    sock[0] = s
    s.settimeout(0.3)
    while not stop[0]:
        try:
            d = s.recv(65536)
        except socket.timeout:
            continue
        except OSError:
            break
        if not d:
            break
        buf.extend(d)
        log.write(d)
        log.flush()


threading.Thread(target=reader, daemon=True).start()


def send(line):
    s = sock[0]
    if s is None:
        return
    try:
        s.sendall(line.encode() + b"\n")
    except OSError as e:
        print("send failed", e)


MARK = b"Freeing unused kernel memory"
t0 = time.time()
while time.time() - t0 < 260:
    if p.poll() is not None:
        stop[0] = True
        err.flush()
        sys.exit(f"QEMU exited before userland (rc={p.returncode}); see /tmp/shr.err")
    if MARK in bytes(buf):
        break
    time.sleep(1)
else:
    print("never reached userland")
    stop[0] = True
    p.terminate()
    sys.exit(1)

t0 = time.time()
while time.time() - t0 < 120:
    if re.search(rb"root@[A-Za-z0-9_.-]+:/#", bytes(buf)):
        break
    time.sleep(1)
# 注意: 提示符可能变成 /tmp/sp/application/bin# (cd 之后), 所以不严格匹配


def run_and_collect(cmd, wait=None):
    if wait is None:
        wait = int(os.environ.get("SP_CMD_WAIT", "25"))
    """执行一条命令，返回切分出来的干净输出。"""
    mk = f"MK{int(time.time() * 1000000) % 1000000}"
    before = len(buf)
    # 命令以 & 结尾(后台执行)时不能再追加 "; echo MK", 否则 shell 语法错误。
    # 这时改成发一条独立的 "echo MK" 让标记照常出现, 便于切分输出。
    if cmd.rstrip().endswith("&"):
        send(cmd)
        time.sleep(0.3)
        send(f"echo {mk}")
    else:
        send(f"{cmd}; echo {mk}")
    t0 = time.time()
    while time.time() - t0 < wait:
        if re.search(rb"(?:^|[\r\n])" + mk.encode() + rb"\r?\n",
                     bytes(buf)[before:]):
            break
        time.sleep(0.3)
    else:
        print(f"WARNING: command completion marker not received after {wait}s")
    raw = bytes(buf)[before:].decode("utf-8", "replace")
    keep = []
    for ln in raw.splitlines():
        if re.match(r"^\s*\[\s*\d+\.\d+\]", ln):
            continue
        if re.match(r"^\d\d-\d\d \d\d:\d\d:\d\d\.\d+", ln):
            continue
        if re.match(r"^\d{2}-\d{2} \d{2}:\d{2}:\d{2}", ln):
            continue
        keep.append(ln)
    return keep


if "--script" in sys.argv:
    path = sys.argv[sys.argv.index("--script") + 1]
    raw = open(path, "rb").read()
    b64 = base64.b64encode(raw).decode()
    # ★ UART 会丢字: 分块 base64 传输必须**逐块校验长度**, 否则脚本静默损坏。
    # 每块独立 base64(固定 48 字节 -> 64 字符), 接收端逐块 base64 -d 后
    # 追加并记录字节数; 发送端比对每块的期望长度, 不符就重发该块。
    CH = 48
    chunks = [b64[i:i + CH] for i in range(0, len(b64), CH)]
    send("rm -f /tmp/_shrun.sh /tmp/_shrun.md5 /tmp/_c.*")
    # ★ 传输策略: 每块写入**自己的文件**(覆盖式, 不用 >> —— 追加在重发时
    # 会重复), 全部送完后由 guest 一次性 cat 拼接, 再核对总长度。
    # UART 会丢字, 所以每块都带序号, 拼接后按长度逐块核对。
    send("rm -f /tmp/_pc*.b64 /tmp/_pc*.bin /tmp/_shrun.sh")
    for idx, ch in enumerate(chunks):
        send(f"printf '%s' '{ch}' > /tmp/_pc{idx}.b64")
    time.sleep(0.25)
    for idx in range(len(chunks)):
        send(f"base64 -d /tmp/_pc{idx}.b64 > /tmp/_pc{idx}.bin 2>/dev/null")
    time.sleep(0.25)
    send("cat /tmp/_pc0.bin /tmp/_pc1.bin > /tmp/_shrun.sh 2>/dev/null")
    for idx in range(2, len(chunks)):
        send(f"cat /tmp/_pc{idx}.bin >> /tmp/_shrun.sh 2>/dev/null")
    time.sleep(0.35)
    send("wc -c /tmp/_shrun.sh > /tmp/_shrun.md5 2>&1")
    time.sleep(0.25)
    tot = 0
    for ln in run_and_collect("cat /tmp/_shrun.md5", wait=25):
        m = re.search(r"(\d+)\s+/tmp/_shrun\.sh", ln)
        if m:
            tot = int(m.group(1))
            break
    if tot != len(raw):
        print(f"WARNING: script transfer incomplete "
              f"(want {len(raw)} got {tot}) -- guest script may be corrupt")
    send("chmod +x /tmp/_shrun.sh")
    send("wc -c /tmp/_shrun.sh > /tmp/_shrun.md5 2>&1")
    send("sh /tmp/_shrun.sh")
    time.sleep(float(os.environ.get("SP_SCRIPT_WAIT", "20")))
    print("=== script finished ===")
    for ln in run_and_collect("cat /tmp/_shrun.md5 2>&1; cat /tmp/_shrun.out 2>&1 || echo NO_OUT", wait=40):
        print("  " + ln[:200])
    sys.stdout.flush()
else:
    for cmd in sys.argv[1:]:
        print(f"\n===== $ {cmd}")
        for ln in run_and_collect(cmd):
            print("  " + ln[:200])
        sys.stdout.flush()

stop[0] = True
p.terminate()
